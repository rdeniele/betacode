// Generates packages/database/src/init-sql.ts from prisma/schema.prisma so the app can create its
// SQLite tables at runtime without needing the Prisma CLI installed.
import { execFileSync } from "node:child_process";
import { writeFileSync } from "node:fs";
import { dirname, join } from "node:path";
import { fileURLToPath } from "node:url";

const root = join(dirname(fileURLToPath(import.meta.url)), "..");
const sql = execFileSync(
  process.execPath,
  [join(root, "node_modules/prisma/build/index.js"), "migrate", "diff", "--from-empty", "--to-schema-datamodel", join(root, "prisma/schema.prisma"), "--script"],
  { cwd: root, env: { ...process.env, DATABASE_URL: "file:./unused.db" }, encoding: "utf8" },
);
const out = `// GENERATED by scripts/gen-db-sql.mjs from prisma/schema.prisma. Do not edit.\nexport const INIT_SQL = ${JSON.stringify(sql)};\n`;
writeFileSync(join(root, "packages/database/src/init-sql.ts"), out);
console.log("wrote packages/database/src/init-sql.ts");
